import type { Config } from "./config.js";
import type { ProfileData } from "./data/types.js";
import { PROJECT_SLOTS } from "./widgets/projects.js";
import { widgets } from "./widgets/index.js";

type Item = { name: string; href?: string; width?: string; height?: number };
type Row = Item[];

function altOf(name: string): string {
  return widgets.find((w) => w.name === name)?.alt ?? name;
}

function picture(base: string, item: Item): string {
  const w = widgets.find((x) => x.name === item.name);
  const ext = w?.kind ?? "svg";
  const src = (theme: string) => `${base}/${item.name}-${theme}.${ext}`;
  const size = item.height ? `height="${item.height}"` : `width="${item.width ?? "100%"}"`;
  const pic = `<picture><source media="(prefers-color-scheme: dark)" srcset="${src("dark")}"><source media="(prefers-color-scheme: light)" srcset="${src("light")}"><img alt="${altOf(item.name)}" src="${src("dark")}" ${size}></picture>`;
  return item.href ? `<a href="${item.href}">${pic}</a>` : pic;
}

/** The README layout: rows of theme-aware pictures, no visible markdown text. */
export function layout(data: ProfileData, config: Config): Row[] {
  const profile = `https://github.com/${config.login}`;
  const repo = data.repos.find((r) => r.name.toLowerCase() !== config.login.toLowerCase() && !r.name.startsWith("."));
  const half = "49%";
  return [
    [{ name: "hero" }],
    [
      { name: "social-linkedin", href: config.links.linkedin, height: 52 },
      { name: "social-instagram", href: config.links.instagram, height: 52 },
      { name: "social-web", href: config.links.website, height: 52 },
      { name: "social-github", href: profile, height: 52 },
    ],
    [{ name: "divider" }],
    [{ name: "terminal" }],
    [{ name: "stats" }],
    [{ name: "contrib" }],
    [{ name: "snake" }],
    [{ name: "pulse" }],
    [
      { name: "skyline", width: half },
      { name: "life", width: half },
    ],
    [{ name: "divider" }],
    [{ name: "now", href: repo?.url ?? `${profile}?tab=repositories` }],
    [{ name: "stack" }],
    [
      { name: "languages", width: half },
      { name: "rhythm", width: half },
    ],
    [{ name: "journey" }],
    [{ name: "board", href: `${profile}?tab=overview` }],
    ...Array.from({ length: PROJECT_SLOTS / 2 }, (_, r): Row =>
      [0, 1].map((c) => {
        const i = r * 2 + c;
        return { name: `project-${i + 1}`, width: half, href: data.projects[i]?.url ?? `${profile}?tab=repositories` };
      }),
    ),
    [
      { name: "trophies", width: half },
      { name: "today", width: half },
    ],
    [{ name: "divider" }],
    [{ name: "footer" }],
  ];
}

export function renderReadme(data: ProfileData, config: Config): string {
  const rows = layout(data, config).map((row) => `<p align="center">\n${row.map((i) => picture(config.assetBase, i)).join("\n")}\n</p>`);
  return `<!--
  This README is generated by generator/ and rebuilt every night by
  .github/workflows/profile.yml. Edit generator/src/readme.ts instead.
-->

${rows.join("\n\n")}
`;
}
